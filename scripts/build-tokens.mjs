// Compiles theme/tokens.json into src/styles/tokens.generated.css (R30, R31, P0.6).
// Usage: node scripts/build-tokens.mjs [--input <tokens.json>] [--output <file.css>]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** @typedef {"color" | "px" | "ms" | "policy"} TokenKind */

/**
 * Every required key path and the kind of value it holds.
 * @type {Readonly<Record<string, TokenKind>>}
 */
export const SCHEMA = Object.freeze({
  "colors.brand.red": "color",
  "colors.brand.steel": "color",
  "colors.bg.canvas": "color",
  "colors.bg.surface": "color",
  "colors.bg.elevated": "color",
  "colors.bg.hover": "color",
  "colors.border.default": "color",
  "colors.border.strong": "color",
  "colors.text.primary": "color",
  "colors.text.secondary": "color",
  "colors.text.muted": "color",
  "colors.state.selected": "color",
  "colors.state.redHover": "color",
  "colors.state.redActive": "color",
  "radii.control": "px",
  "radii.card": "px",
  "radii.dialog": "px",
  "motion.fast": "ms",
  "motion.panel": "ms",
  "motion.reduced": "policy",
});

/** @type {Readonly<Record<TokenKind, { test: (value: string) => boolean, label: string }>>} */
const KINDS = {
  color: {
    test: (value) => /^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i.test(value),
    label: "a hex color",
  },
  px: { test: (value) => /^\d+(?:\.\d+)?px$/.test(value), label: "a px length" },
  ms: { test: (value) => /^\d+(?:\.\d+)?ms$/.test(value), label: "a ms duration" },
  policy: { test: (value) => value.trim().length > 0, label: "a non-empty text" },
};

/**
 * Leaf values of a JSON object by dotted key path.
 * @param {unknown} node
 * @param {string} [prefix]
 * @returns {Map<string, unknown>}
 */
export function flatten(node, prefix = "") {
  /** @type {Map<string, unknown>} */
  const leaves = new Map();
  if (node !== null && typeof node === "object" && !Array.isArray(node)) {
    for (const [key, value] of Object.entries(node)) {
      for (const [path, leaf] of flatten(value, prefix ? `${prefix}.${key}` : key)) {
        leaves.set(path, leaf);
      }
    }
  } else if (prefix) {
    leaves.set(prefix, node);
  }
  return leaves;
}

/**
 * Checks the token file shape.
 * @param {unknown} tokens parsed tokens.json
 * @returns {{ errors: string[], warnings: string[], values: Map<string, string> }}
 */
export function validateTokens(tokens) {
  const leaves = flatten(tokens);
  /** @type {string[]} */
  const errors = [];
  /** @type {Map<string, string>} */
  const values = new Map();
  for (const [path, kind] of Object.entries(SCHEMA)) {
    if (!leaves.has(path)) {
      errors.push(`${path} is missing`);
      continue;
    }
    const value = leaves.get(path);
    if (typeof value !== "string" || !KINDS[kind].test(value)) {
      errors.push(`${path} must be ${KINDS[kind].label}, got ${JSON.stringify(value)}`);
      continue;
    }
    values.set(path, value);
  }
  const warnings = [...leaves.keys()]
    .filter((path) => !(path in SCHEMA))
    .map((path) => `${path} is not a known token and is ignored`);
  return { errors, warnings, values };
}

/** @param {string} name */
function kebab(name) {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/**
 * CSS for valid token values: a Tailwind v4 `@theme` block and `:root` motion variables.
 * @param {Map<string, string>} values
 * @returns {string}
 */
export function renderCss(values) {
  /** @type {string[]} */
  const theme = [];
  /** @type {string[]} */
  const root = [];
  for (const [path, value] of values) {
    const [group, ...rest] = path.split(".");
    const name = rest.map(kebab).join("-");
    if (group === "colors") theme.push(`  --color-${name}: ${value};`);
    if (group === "radii") theme.push(`  --radius-${name}: ${value};`);
    // motion.reduced is a policy, not a value (globals.css holds the reduced-motion rule).
    if (group === "motion" && SCHEMA[path] === "ms") root.push(`  --clawdio-motion-${name}: ${value};`);
  }
  theme.push("  --default-transition-duration: var(--clawdio-motion-fast);");
  return [
    "/* Generated by scripts/build-tokens.mjs from theme/tokens.json. Do not edit. */",
    "@theme {",
    ...theme,
    "}",
    "",
    ":root {",
    ...root,
    "}",
    "",
  ].join("\n");
}

/**
 * Reads, validates and writes. Throws with every error when the token file is invalid.
 * @param {{ input: string, output: string }} options
 * @returns {{ warnings: string[] }}
 */
export function buildTokens({ input, output }) {
  /** @type {unknown} */
  let tokens;
  try {
    tokens = JSON.parse(readFileSync(input, "utf8"));
  } catch (error) {
    throw new Error(`cannot read ${input}: ${error instanceof Error ? error.message : String(error)}`, {
      cause: error,
    });
  }
  const { errors, warnings, values } = validateTokens(tokens);
  if (errors.length > 0) {
    throw new Error(`invalid ${input}\n${errors.map((error) => `  - ${error}`).join("\n")}`);
  }
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, renderCss(values));
  return { warnings };
}

/** @param {string[]} argv */
function parseArgs(argv) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  /** @param {string} flag */
  const option = (flag) => {
    const index = argv.indexOf(flag);
    return index >= 0 ? argv[index + 1] : undefined;
  };
  return {
    input: resolve(option("--input") ?? resolve(root, "theme/tokens.json")),
    output: resolve(option("--output") ?? resolve(root, "src/styles/tokens.generated.css")),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const options = parseArgs(process.argv.slice(2));
    const { warnings } = buildTokens(options);
    for (const warning of warnings) console.warn(`tokens: ${warning}`);
    console.log(`tokens: wrote ${options.output}`);
  } catch (error) {
    console.error(`tokens: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
